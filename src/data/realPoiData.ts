/**
 * 查询 POI 分类名称
 */
export function getPoiCategoryName(code: string): string {
  const mainCode = code.substring(0, 2);
  const subCode = code.substring(0, 4);
  const mainCategory = POI_CATEGORIES[mainCode as keyof typeof POI_CATEGORIES];
  if (mainCategory) {
    const subCategory = mainCategory.sub[subCode as keyof typeof mainCategory.sub];
    if (subCategory) {
      return subCategory;
    }
    return mainCategory.name;
  }
  return '未知分类';
}

