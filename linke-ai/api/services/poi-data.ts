export const estimateAudience = (p: RealPOI | { category: string; scale: number }): number => {
  switch (p.category) {
    case 'office':
    case 'cbd':
    case 'industrial':
      return Math.round(p.scale * 0.8);
    case 'residence':
    case 'community':
      return Math.round(p.scale * 2.6);
    case 'mall':
    case 'street':
      return Math.round(p.scale * 0.05);
    case 'school':
      return Math.round(p.scale * 0.6);
    case 'subway':
      return Math.round(p.scale * 0.15);
    case 'park':
      return Math.round(p.scale * 0.04);
    default:
      return p.scale;
  }
};

// 按城市分组
export const POI_BY_CITY = NATIONAL_POI.reduce((acc, poi) => {
  const key = poi.city;
  if (!acc[key]) acc[key] = [];
  acc[key].push(poi);
  return acc;
}, {} as Record<string, typeof NATIONAL_POI>);

// 按省份分组
export const POI_BY_PROVINCE = NATIONAL_POI.reduce((acc, poi) => {
  const key = poi.province;
  if (!acc[key]) acc[key] = [];
  acc[key].push(poi);
  return acc;
}, {} as Record<string, typeof NATIONAL_POI>);

