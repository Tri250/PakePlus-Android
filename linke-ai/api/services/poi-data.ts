// 按城市+区县分组(用于层级筛选)
export const POI_BY_CITY_DISTRICT = NATIONAL_POI.reduce((acc, poi) => {
  if (!acc[poi.city]) acc[poi.city] = {};
  const d = poi.district || '其他';
  if (!acc[poi.city][d]) acc[poi.city][d] = [];
  acc[poi.city][d].push(poi);
  return acc;
}, {} as Record<string, Record<string, typeof NATIONAL_POI>>);
